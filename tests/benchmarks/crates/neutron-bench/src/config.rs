//! Server configuration generation for each server type.

use eyre::{Result, WrapErr};
use std::fs;
use std::path::Path;

/// Ensure server and log directories exist.
pub fn ensure_dirs(server_dir: &Path, log_dir: &Path) -> Result<()> {
    fs::create_dir_all(server_dir)
        .wrap_err_with(|| format!("creating server dir: {}", server_dir.display()))?;
    fs::create_dir_all(log_dir)
        .wrap_err_with(|| format!("creating log dir: {}", log_dir.display()))?;
    Ok(())
}

/// Generate server.properties for Java servers (vanilla, paper, folia).
pub fn write_server_properties(
    server_dir: &Path,
    max_players: usize,
    seed: &str,
    run_id: &str,
) -> Result<()> {
    // Use max(max_players, 100) to avoid "server full" with Folia/Paper
    let effective_max = max_players.max(100);
    let content = format!(
        r#"# Auto-generated by neutron-bench for run: {}
eula=true
online-mode=false
level-seed={}
view-distance=10
simulation-distance=10
level-name={}
max-players={}
white-list=false
spawn-protection=0
spawn-animals=false
spawn-monsters=false
spawn-npcs=false
allow-nether=false
allow-end=false
difficulty=peaceful
enable-rcon=true
rcon.port=25575
rcon.password=neutronbench
broadcast-rcon-to-ops=false
"#,
        run_id, seed, run_id, effective_max
    );

    let path = server_dir.join("server.properties");
    fs::write(&path, &content)
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    // Also write eula.txt
    let eula_path = server_dir.join("eula.txt");
    fs::write(&eula_path, "eula=true\n")
        .wrap_err_with(|| format!("writing {}", eula_path.display()))?;

    Ok(())
}

/// Generate paper-global.yml with spark enabled.
pub fn write_paper_global(server_dir: &Path) -> Result<()> {
    let config_dir = server_dir.join("config");
    fs::create_dir_all(&config_dir)?;

    // Spark in Paper 26.2: enable-immediately starts the background profiler.
    // TPS is measured via RCON (spark tps command), not HTTP.
    let content = r#"# Auto-generated by neutron-bench
spark:
  enabled: true
  enable-immediately: true

version: 29
"#;

    let path = config_dir.join("paper-global.yml");
    fs::write(&path, content)
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    Ok(())
}

/// Generate pumpkin.toml for Pumpkin server.
///
/// Critical settings for offline mode:
/// - `encryption = false`: Skips RSA key exchange (like vanilla offline mode)
/// - `online_mode = false`: Skips Mojang session server auth
/// - `compression enabled = false`: Avoids LZ4 vs zlib incompatibility with azalea
pub fn write_pumpkin_config(
    server_dir: &Path,
    max_players: usize,
    seed: &str,
    run_id: &str,
) -> Result<()> {
    let content = format!(
        r#"# Auto-generated by neutron-bench for run: "{run_id}"
# Offline mode: encryption=false, online_mode=false, compression disabled

[networking]
port = 25565
max_players = {max_players}

[networking.java]
online_mode = false
encryption = false
address = "0.0.0.0:25565"

[networking.java.compression]
enabled = false

[networking.java.authentication]
enabled = false

[motd]
single = "Neutron Benchmark Server"

[world]
seed = "{seed}"
view_distance = 10
simulation_distance = 10
level_name = "{run_id}"
"#,
        run_id = run_id,
        max_players = max_players,
        seed = seed,
    );

    // Write as pumpkin.toml (Pumpkin's expected config file)
    let path = server_dir.join("pumpkin.toml");
    fs::write(&path, &content)
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    // Remove any old config.toml
    let old_config = server_dir.join("config.toml");
    let _ = fs::remove_file(old_config);

    Ok(())
}
