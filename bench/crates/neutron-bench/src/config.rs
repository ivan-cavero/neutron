//! Server configuration generation for each server type.

use eyre::{Result, WrapErr};
use std::fs;
use std::path::Path;

/// Ensure server and log directories exist.
pub fn ensure_dirs(server_dir: &Path, log_dir: &Path) -> Result<()> {
    fs::create_dir_all(server_dir)
        .wrap_err_with(|| format!("creating server dir: {}", server_dir.display()))?;
    fs::create_dir_all(log_dir)
        .wrap_err_with(|| format!("creating log dir: {}", log_dir.display()))?;
    Ok(())
}

/// Generate server.properties for Java servers (vanilla, paper, folia).
pub fn write_server_properties(
    server_dir: &Path,
    max_players: usize,
    seed: &str,
    run_id: &str,
) -> Result<()> {
    let content = format!(
        r#"# Auto-generated by neutron-bench for run: {}
eula=true
online-mode=false
level-seed={}
view-distance=10
simulation-distance=10
level-name={}
max-players={}
white-list=false
spawn-protection=0
spawn-animals=false
spawn-monsters=false
spawn-npcs=false
allow-nether=false
allow-end=false
difficulty=peaceful
"#,
        run_id, seed, run_id, max_players
    );

    let path = server_dir.join("server.properties");
    fs::write(&path, &content)
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    // Also write eula.txt
    let eula_path = server_dir.join("eula.txt");
    fs::write(&eula_path, "eula=true\n")
        .wrap_err_with(|| format!("writing {}", eula_path.display()))?;

    Ok(())
}

/// Generate config.toml for Pumpkin server.
pub fn write_pumpkin_config(
    server_dir: &Path,
    max_players: usize,
    seed: &str,
    run_id: &str,
) -> Result<()> {
    let content = format!(
        r#"# Auto-generated by neutron-bench for run: {}
[general]
online_mode = false
seed = {}
view_distance = 10
simulation_distance = 10
level_name = {}
max_players = {}

[server]
port = 25565
address = "127.0.0.1"

[motd]
single = "Neutron Benchmark Server"
"#,
        run_id, seed, run_id, max_players
    );

    let path = server_dir.join("config.toml");
    fs::write(&path, &content)
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    Ok(())
}
